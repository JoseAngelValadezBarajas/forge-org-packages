import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const packageRoot = resolve(import.meta.dirname, '..');
const file = resolve(packageRoot, 'tokens.json');
const output = resolve(packageRoot, 'src/tokens.css');
const data = JSON.parse(readFileSync(file, 'utf8'));
const name = (value) => value.replace(/[A-Z]/g, (character) => `-${character.toLowerCase()}`);
const declarations = (object, prefix = '') =>
  Object.entries(object)
    .map(([key, value]) => `  --forge-${prefix}${name(key)}: ${value};`)
    .join('\n');
const paletteDeclarations = Object.entries(data.palette)
  .flatMap(([palette, shades]) =>
    Object.entries(shades).map(([shade, value]) => `  --forge-palette-${palette}-${shade}: ${value};`),
  )
  .join('\n');
const content = `/* GENERATED by the public package token generator. Do not edit. */
:root, [data-theme="dark"] {
  color-scheme: dark;
${declarations(data.colors.dark)}
${declarations(data.semantic.dark)}
}
[data-theme="light"] {
  color-scheme: light;
${declarations(data.colors.light)}
${declarations(data.semantic.light)}
}
:root {
${paletteDeclarations}
${declarations(data.spacing, 'space-')}
${declarations(data.radius, 'radius-')}
${declarations(data.type, 'font-')}
${declarations(data.fontWeight, 'font-weight-')}
${declarations(data.shadow, 'shadow-')}
${declarations(data.motion, 'motion-')}
${declarations(data.breakpoint, 'breakpoint-')}
${declarations(data.border, 'border-')}
${declarations(data.fontSize, 'font-size-')}
${declarations(data.lineHeight, 'line-height-')}
}
`;

if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== content) {
    console.error('Design tokens CSS is stale; run npm run build --workspace=@corefoundry-labs/forge-tokens');
    process.exit(1);
  }
  console.log('Design tokens CSS matches the source JSON');
} else {
  writeFileSync(output, content);
  console.log(`Wrote ${output}`);
}
